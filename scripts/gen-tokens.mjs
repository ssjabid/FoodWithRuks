// Writes src/lib/tokens.ts from the --color-* hex values in src/styles/globals.css (Daylight = :root,
// After hours = .dark) so the generated images (OG cards, Apple icon, favicon) never carry their own hex.
// Usage: node scripts/gen-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../src/styles/globals.css", import.meta.url), "utf8");

function braced(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    if (text[i] === "{") depth++;
    else if (text[i] === "}" && --depth === 0) return text.slice(open + 1, i);
  }
  return text.slice(open + 1);
}
function blocks(selector) {
  const out = [];
  const re = new RegExp(`(^|[\\n}])\\s*${selector.replace(/[.:]/g, "\\$&")}\\s*\\{`, "g");
  let m;
  while ((m = re.exec(css))) out.push(braced(css, css.indexOf("{", m.index + m[0].length - 1)));
  return out;
}
function tokensIn(bodies) {
  const vars = {};
  for (const body of bodies)
    for (const line of body.split(";")) {
      const kv = line.match(/--color-([a-z0-9-]+):\s*(#[0-9A-Fa-f]{6})\b/);
      if (kv) vars[kv[1]] = kv[2].toUpperCase();
    }
  return vars;
}

const light = tokensIn(blocks(":root"));
const dark = tokensIn(blocks(".dark"));
const missing = Object.keys(light).filter((k) => !dark[k]);
if (missing.length) console.warn("dark mode is missing:", missing.join(", "));

const fmt = (o) =>
  "{\n" +
  Object.entries(o)
    .map(([k, v]) => `    ${JSON.stringify(k)}: "${v}",`)
    .join("\n") +
  "\n  }";
const out = `// Generated by scripts/gen-tokens.mjs from src/styles/globals.css. Do not edit; run \`npm run gen:tokens\`.
// The literal hex for both modes, for places that cannot read CSS variables (OG images, icons).

export const TOKENS = {
  light: ${fmt(light)},
  dark: ${fmt(dark)},
} as const;

export type TokenName = keyof typeof TOKENS.light;

export function token(name: TokenName, mode: "light" | "dark" = "light"): string {
  return (TOKENS[mode] as Record<string, string>)[name] ?? TOKENS.light[name];
}
`;
writeFileSync(new URL("../src/lib/tokens.ts", import.meta.url), out);
console.log(`src/lib/tokens.ts: ${Object.keys(light).length} light tokens, ${Object.keys(dark).length} dark tokens`);
